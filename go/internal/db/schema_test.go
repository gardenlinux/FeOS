var update = flag.Bool("update", false, "rewrite testdata/schema.golden from the migrated database")

// dumpSchema describes the public schema of q's database: every table that
// is not a partition, with its columns (type, nullability, default,
// identity), its constraints, its indexes and its partitioning, in a stable
// order and in PostgreSQL's own rendering. The order is bytewise (COLLATE
// "C"), whatever the database's collation: en_US.utf8 ignores punctuation
// and puts "CHECK ((b" before "CHECK (((a".
func dumpSchema(ctx context.Context, t *testing.T, q db.Querier) string {
	t.Helper()
	var b strings.Builder
	rows, err := q.Query(ctx, `SELECT c.oid, c.relname, coalesce(pg_get_partkeydef(c.oid), ''),
			coalesce(array_to_string(c.reloptions, ','), '')
		FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relispartition
		ORDER BY c.relname`)
	if err != nil {
		t.Fatal(err)
	}
	type table struct {
		oid                 uint32
		name, part, options string
	}
	tables, err := pgx.CollectRows(rows, func(r pgx.CollectableRow) (table, error) {
		var tb table
		err := r.Scan(&tb.oid, &tb.name, &tb.part, &tb.options)
		return tb, err
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, tb := range tables {
		fmt.Fprintf(&b, "TABLE %s", tb.name)
		if tb.part != "" {
			fmt.Fprintf(&b, " PARTITION BY %s", tb.part)
		}
		if tb.options != "" {
			fmt.Fprintf(&b, " WITH (%s)", tb.options)
		}
		b.WriteString("\n")
		rows, err := q.Query(ctx, `SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
				coalesce(pg_get_expr(d.adbin, d.adrelid), ''), a.attidentity::text,
				coalesce((SELECT quote_ident(c.collname) FROM pg_collation c
					WHERE c.oid = a.attcollation AND c.oid <> 'default'::regcollation), '')
			FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
			WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, tb.oid)
		if err != nil {
			t.Fatal(err)
		}
		cols, err := pgx.CollectRows(rows, func(r pgx.CollectableRow) (string, error) {
			var name, typ, def, identity, collation string
			var notNull bool
			if err := r.Scan(&name, &typ, &notNull, &def, &identity, &collation); err != nil {
				return "", err
			}
			s := "  COLUMN " + name + " " + typ
			if collation != "" {
				s += " COLLATE " + collation
			}
			if notNull {
				s += " NOT NULL"
			}
			if def != "" {
				s += " DEFAULT " + def
			}
			switch identity {
			case "a":
				s += " GENERATED ALWAYS AS IDENTITY"
			case "d":
				s += " GENERATED BY DEFAULT AS IDENTITY"
			}
			return s, nil
		})
		if err != nil {
			t.Fatal(err)
		}
		for _, c := range cols {
			b.WriteString(c + "\n")
		}
		rows, err = q.Query(ctx, `SELECT pg_get_constraintdef(oid) FROM pg_constraint
			WHERE conrelid = $1 ORDER BY contype, pg_get_constraintdef(oid) COLLATE "C"`, tb.oid)
		if err != nil {
			t.Fatal(err)
		}
		cons, err := pgx.CollectRows(rows, pgx.RowTo[string])
		if err != nil {
			t.Fatal(err)
		}
		for _, c := range cons {
			b.WriteString("  CONSTRAINT " + c + "\n")
		}
		rows, err = q.Query(ctx, `SELECT pg_get_indexdef(i.indexrelid) FROM pg_index i
			WHERE i.indrelid = $1 ORDER BY pg_get_indexdef(i.indexrelid) COLLATE "C"`, tb.oid)
		if err != nil {
			t.Fatal(err)
		}
		idx, err := pgx.CollectRows(rows, pgx.RowTo[string])
		if err != nil {
			t.Fatal(err)
		}
		for _, i := range idx {
			b.WriteString("  " + i + "\n")
		}
	}
	return b.String()
}

// The migration applies to an empty database and yields exactly the schema
// of the design (testdata/schema.golden, checked against it by hand).
func TestMigrationSchema(t *testing.T) {
	t.Parallel()
	d := dbtest.Open(t)
	ctx := context.Background()
	if err := d.Migrate(ctx, nil); err != nil {
		t.Fatal(err)
	}
	got := dumpSchema(ctx, t, d.Pool)
	const golden = "testdata/schema.golden"
	if *update {
		if err := os.WriteFile(golden, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if got != string(want) {
		gl, wl := strings.Split(got, "\n"), strings.Split(string(want), "\n")
		for i := 0; i < max(len(gl), len(wl)); i++ {
			var g, w string
			if i < len(gl) {
				g = gl[i]
			}
			if i < len(wl) {
				w = wl[i]
			}
			if g != w {
				t.Fatalf("schema differs from %s at line %d:\n got: %s\nwant: %s", golden, i+1, g, w)
			}
		}
	}

	// The tables the design names, and no others.
	var tables []string
	rows, err := d.Pool.Query(ctx, `SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relispartition ORDER BY 1`)
	if err != nil {
		t.Fatal(err)
	}
	tables, err = pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		t.Fatal(err)
	}
	wantTables := []string{"activity", "auth_logins", "bookings", "cluster_secrets",
		"domains", "env_attached", "env_incidents",
		"env_instances", "env_job_runs", "env_releases", "env_route_tokens", "env_secrets", "env_tags", "env_volumes",
		"environments", "event_gaps", "host_labels", "image_bakes", "ingress_certs", "ingresses", "instances",
		"issued_certs", "join_tokens", "kube_bindings", "leases", "node_certs", "node_starts", "node_telemetry",
		"nodes", "pod_network", "pod_tombstones", "sandbox_holds", "sandbox_tokens", "sandboxes",
		"schema_migrations", "ssh_bindings", "tenant_tokens", "tenants", "tool_calls", "traffic_records",
		"ui_sessions", "watches"}
	if strings.Join(tables, ",") != strings.Join(wantTables, ",") {
		t.Fatalf("tables %v, want %v", tables, wantTables)
	}
}
